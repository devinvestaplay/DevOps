import { boolean, foreignKey, index, int, json, mysqlEnum, mysqlTable, timestamp, uniqueIndex, varchar } from "drizzle-orm/mysql-core";

export const projects = mysqlTable("projects", {
  id: varchar("id", { length: 36 }).primaryKey(),
  name: varchar("name", { length: 120 }).notNull(),
  slug: varchar("slug", { length: 80 }).notNull(),
  description: varchar("description", { length: 2000 }).notNull().default(""),
  status: mysqlEnum("status", ["active", "archived"]).notNull().default("active"),
  createdAt: timestamp("created_at", { fsp: 3 }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { fsp: 3 }).notNull().defaultNow(),
}, (table) => [uniqueIndex("projects_slug_unique").on(table.slug)]);

export const environments = mysqlTable("environments", {
  id: varchar("id", { length: 36 }).primaryKey(),
  projectId: varchar("project_id", { length: 36 }).notNull(),
  name: varchar("name", { length: 120 }).notNull(),
  type: mysqlEnum("type", ["development", "staging", "production"]).notNull(),
  status: mysqlEnum("status", ["active", "disabled"]).notNull().default("active"),
  createdAt: timestamp("created_at", { fsp: 3 }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { fsp: 3 }).notNull().defaultNow(),
}, (table) => [
  foreignKey({ name: "environments_project_fk", columns: [table.projectId], foreignColumns: [projects.id] }),
  uniqueIndex("environments_project_name_unique").on(table.projectId, table.name),
  uniqueIndex("environments_project_id_unique").on(table.projectId, table.id),
  index("environments_project_idx").on(table.projectId),
]);

